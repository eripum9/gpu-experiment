#!/usr/bin/env python3
"""Embed the one pinned PSP 14.0.2 SOS package used by standalone survey."""
from __future__ import annotations

import argparse
import hashlib
import os
from pathlib import Path
import tempfile

PINNED_SIZE = 421216
PINNED_SHA256 = "7b538448b57d4f9dd06b2eea90d4f86a16e65e3027cdecee8db71c2c5f1fa243"
DEFAULT_INPUT = Path(__file__).resolve().parents[2] / "src/navi48-bringup/firmware/psp_14_0_2_sos.bin"


def render_cpp_unchecked(data: bytes) -> str:
    """Render bytes as immutable C++ storage; callers decide whether data is trusted."""
    if not data:
        raise ValueError("firmware input must not be empty")
    digest = hashlib.sha256(data).hexdigest()
    lines = []
    for start in range(0, len(data), 12):
        chunk = data[start:start + 12]
        lines.append("\t" + ", ".join(f"0x{byte:02x}" for byte in chunk) + ",")
    return (
        "// Generated by tools/navi44-survey/embed_psp.py; do not edit.\n"
        f"// PSP 14.0.2 SOS: {len(data)} bytes, sha256={digest}\n"
        '#include "psp_firmware.hpp"\n\n'
        "namespace cobalt {\nnamespace survey {\nnamespace {\n"
        "alignas(16) const uint8_t kPsp1402Firmware[] = {\n"
        + "\n".join(lines)
        + "\n};\n} // namespace\n\n"
        "FirmwareView psp1402Firmware() {\n"
        "\treturn {kPsp1402Firmware, sizeof(kPsp1402Firmware)};\n"
        "}\n\n} // namespace survey\n} // namespace cobalt\n"
    )


def verify_pinned(data: bytes, label: str = "firmware input") -> None:
    digest = hashlib.sha256(data).hexdigest()
    if len(data) != PINNED_SIZE or digest != PINNED_SHA256:
        raise ValueError(
            f"{label} does not match pinned PSP 14.0.2 SOS: "
            f"got {len(data)} bytes sha256={digest}; expected "
            f"{PINNED_SIZE} bytes sha256={PINNED_SHA256}"
        )


def generate(source: Path, output: Path) -> None:
    # Read and validate fully before creating directories or temporary output.
    data = source.read_bytes()
    verify_pinned(data, str(source))
    rendered = render_cpp_unchecked(data).encode("ascii")

    output.parent.mkdir(parents=True, exist_ok=True)
    temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="wb", prefix=f".{output.name}.", suffix=".tmp",
            dir=output.parent, delete=False,
        ) as temp:
            temp_path = Path(temp.name)
            temp.write(rendered)
            temp.flush()
            os.fsync(temp.fileno())
        os.replace(temp_path, output)
        temp_path = None
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    try:
        generate(args.input, args.output)
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
